// Database snapshot helper, shared by the daily scheduler, the admin download and `npm run backup`.
import { mkdir, readdir, rm, stat } from "node:fs/promises";
import path from "node:path";
import type { PrismaClient } from "@prisma/client";

const STORAGE_DIR = process.env.STORAGE_DIR || path.join(process.cwd(), "storage");
export const BACKUP_DIR = path.join(STORAGE_DIR, "backups");
const KEEP = 30;

/** Write a consistent copy of the SQLite DB via VACUUM INTO. Returns the file path. */
export async function snapshotDb(db: PrismaClient, name?: string) {
  await mkdir(BACKUP_DIR, { recursive: true });
  const stamp = new Date().toISOString().replace(/[:.]/g, "-").slice(0, 19);
  const file = path.join(BACKUP_DIR, name ?? `biesf-${stamp}.db`);
  await rm(file, { force: true });
  // Path is generated by us (no user input), so interpolating is safe.
  await db.$executeRawUnsafe(`VACUUM INTO '${file.replace(/'/g, "''")}'`);
  return file;
}

/** Keep only the newest KEEP daily backups. */
export async function pruneBackups() {
  const files = (await readdir(BACKUP_DIR)).filter((f) => /^biesf-.*\.db$/.test(f)).sort();
  for (const f of files.slice(0, Math.max(0, files.length - KEEP))) await rm(path.join(BACKUP_DIR, f));
}

export async function lastBackupAge() {
  try {
    const files = (await readdir(BACKUP_DIR)).filter((f) => /^biesf-.*\.db$/.test(f)).sort();
    if (!files.length) return Infinity;
    const s = await stat(path.join(BACKUP_DIR, files[files.length - 1]));
    return Date.now() - s.mtimeMs;
  } catch {
    return Infinity;
  }
}

export async function runDailyBackup(db: PrismaClient) {
  const file = await snapshotDb(db);
  await pruneBackups();
  console.log("[backup] saved", file);
}
